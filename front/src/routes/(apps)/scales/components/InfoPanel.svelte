<div class="contents">
    <p>
        This is a tool to visualize music scales. Select a tonic note, a scale and a mode in <b
            >Scale selector</b
        >. The page shows the degrees of the scale and displays these notes on the neck of a guitar
        or on a piano in the <b>Notes on instrument</b> section.
    </p>
    <p>
        The <b>Chord progressions</b> section contains a list of chord progressions I took from David
        Benett's videos and other online resources.
    </p>
    <p>The chord progressions update according to the selected scale.</p>
